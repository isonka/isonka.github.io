/**
 * Turns site/routes.ts into build artefacts:
 *   .routes-manifest.json — build-only, read by the shell and prerender scripts
 *   dist/sitemap.xml      — generated, so it can never drift from the routes
 *
 * Run after `vite build`. Reads the TypeScript manifest directly through
 * Node's type stripping, so there is no separate compile step.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { routes, shellPaths, prerenderPaths, canonicalOverrides, shellMeta, BASE_URL } from '../site/routes.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, '..');
const distDir = path.join(projectRoot, 'dist');

if (!fs.existsSync(distDir)) {
  console.error('✗ dist/ not found — run vite build first.');
  process.exit(1);
}

const duplicates = shellPaths.filter((p, i) => shellPaths.indexOf(p) !== i);
if (duplicates.length) {
  console.error(`✗ Duplicate route paths in site/routes.ts: ${[...new Set(duplicates)].join(', ')}`);
  process.exit(1);
}

const malformed = shellPaths.filter((p) => !p.startsWith('/') || !p.endsWith('/'));
if (malformed.length) {
  console.error(`✗ Route paths must start and end with "/": ${malformed.join(', ')}`);
  process.exit(1);
}

const manifest = {
  generatedAt: new Date().toISOString(),
  baseUrl: BASE_URL,
  shellPaths,
  prerenderPaths,
  canonicalOverrides,
  shellMeta,
};

fs.writeFileSync(path.join(projectRoot, '.routes-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

const escapeXml = (value) =>
  value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');

const sitemapRoutes = routes.filter((route) => route.sitemap);

const urlBlocks = sitemapRoutes.map((route) => {
  const { lastmod, changefreq, priority, image } = route.sitemap;
  const lines = [
    '  <url>',
    `    <loc>${BASE_URL}${route.path}</loc>`,
    `    <lastmod>${lastmod}</lastmod>`,
    `    <changefreq>${changefreq}</changefreq>`,
    `    <priority>${priority}</priority>`,
  ];

  if (image) {
    lines.push(
      '    <image:image>',
      `      <image:loc>${escapeXml(image.loc)}</image:loc>`,
      `      <image:title>${escapeXml(image.title)}</image:title>`,
      '    </image:image>',
    );
  }

  lines.push('  </url>');
  return lines.join('\n');
});

const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/generate-routes-manifest.js from site/routes.ts — do not edit by hand -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
  '        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">',
  ...urlBlocks,
  '</urlset>',
  '',
].join('\n');

fs.writeFileSync(path.join(distDir, 'sitemap.xml'), sitemap);

console.log(
  `✓ .routes-manifest.json — ${shellPaths.length} routes, ${prerenderPaths.length} prerendered\n` +
    `✓ sitemap.xml — ${sitemapRoutes.length} URLs (${shellPaths.length - sitemapRoutes.length} excluded)`,
);
